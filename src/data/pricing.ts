export function calculateServicePrice(config: ServiceConfig): number {
  const service = services.find((s) => s.id === config.serviceId);
  if (!service) return 0;
  const base = service.basePrice + service.pricePerUnit * config.units;
  const revisionsPrice = revisionsOptions.find((r) => r.value === config.revisions)?.price || 0;
  return Math.round(base + revisionsPrice);
}

export function calculateServiceTimeline(config: ServiceConfig): number {
  const service = services.find((s) => s.id === config.serviceId);
  if (!service) return 0;
  const extraUnits = Math.max(0, config.units - 1);
  return Math.ceil(service.timelineDays + service.timelinePerUnit * extraUnits);
}

export function formatTimeline(days: number): string {
  if (days < 1) return '1 день';
  const lastDigit = days % 10;
  const lastTwoDigits = days % 100;
  if (lastTwoDigits >= 11 && lastTwoDigits <= 19) return `${days} дней`;
  if (lastDigit === 1) return `${days} день`;
  if (lastDigit >= 2 && lastDigit <= 4) return `${days} дня`;
  return `${days} дней`;
}
